import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { TOOL_CONTRACTS } from '../src/webmcp/contracts.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const modulePath = join(root, 'src', 'webmcp', 'generated', 'tool-validators.js');
const declarationPath = join(root, 'src', 'webmcp', 'generated', 'tool-validators.d.ts');
const checkOnly = process.argv.slice(2).includes('--check');

assert.deepEqual(
  process.argv.slice(2).filter((argument) => argument !== '--check'),
  [],
  'DOMHAMSTER_VALIDATOR_GENERATOR_UNKNOWN_ARGUMENT',
);

const ajv = new Ajv({
  allErrors: true,
  strict: true,
  validateFormats: false,
  code: { source: true, esm: true },
});

for (const contract of TOOL_CONTRACTS) {
  assert.match(contract.name, /^[A-Za-z_$][A-Za-z0-9_$]*$/u);
  ajv.addSchema(structuredClone(contract.inputSchema), contract.name);
}

const exportsByName = Object.fromEntries(
  TOOL_CONTRACTS.map((contract) => [contract.name, contract.name]),
);
const generatedCode = standaloneCode(ajv, exportsByName);
const commonJsUnicodeLength = 'require("ajv/dist/runtime/ucs2length").default';
const portableGeneratedCode = generatedCode.replaceAll(
  commonJsUnicodeLength,
  '((value) => Array.from(value).length)',
);

assert.equal(generatedCode.includes('new Function'), false);
assert.equal(generatedCode.includes('eval('), false);

const moduleSource = [
  '// Generated by scripts/generate-tool-validators.mjs. Do not edit.',
  '/* eslint-disable */',
  portableGeneratedCode,
  '',
].join('\n');
assert.equal(
  moduleSource.includes('require('),
  false,
  'DOMHAMSTER_GENERATED_VALIDATOR_COMMONJS_RUNTIME',
);
const declarationSource = [
  '// Generated by scripts/generate-tool-validators.mjs. Do not edit.',
  "import type { ValidateFunction } from 'ajv';",
  '',
  ...TOOL_CONTRACTS.map((contract) => `export const ${contract.name}: ValidateFunction;`),
  '',
].join('\n');

const outputs = [
  [modulePath, moduleSource],
  [declarationPath, declarationSource],
];

if (checkOnly) {
  for (const [path, expected] of outputs) {
    const actual = await readFile(path, 'utf8').catch(() => '');
    assert.equal(actual, expected, `DOMHAMSTER_GENERATED_VALIDATOR_STALE:${path}`);
  }
  console.log(`DOMHAMSTER_GENERATED_VALIDATOR_PASS tools=${TOOL_CONTRACTS.length}`);
} else {
  await mkdir(dirname(modulePath), { recursive: true });
  await Promise.all(outputs.map(([path, source]) => writeFile(path, source, 'utf8')));
  console.log(`DOMHAMSTER_GENERATED_VALIDATOR_CREATED tools=${TOOL_CONTRACTS.length}`);
}
